// Pins the Android NDK version used by the generated Gradle project.
//
// DARR-41 crash: the release APK died instantly in MainApplication.onCreate
// with SoLoaderDSONotFoundError for libfbjni.so, because libfbjni needs the
// libc++ symbol __cxa_init_primary_exception and the NDK 27 libc++_shared.so
// that React Native 0.86 pins (27.1.12297006) does not export it (verified
// with readelf on the release APK and on the CI runner: NDK 27 count 0,
// NDK 29 count 1 for both arm64-v8a and x86_64).
//
// The generated android/app/build.gradle sets
// `ndkVersion rootProject.ext.ndkVersion` (the RN-pinned 27), and android/
// is regenerated by every clean prebuild, so the pin has to live here as a
// config plugin, not as an edit to the generated file. Failing loudly when
// the expected line is absent keeps a future template change from silently
// shipping the NDK 27 runtime again.
const { withAppBuildGradle } = require("@expo/config-plugins");

const NDK_VERSION = "29.0.14206865";

module.exports = function withNdkVersion(config) {
  return withAppBuildGradle(config, (config) => {
    const before = config.modResults.contents;
    const pattern = "ndkVersion rootProject.ext.ndkVersion";
    if (!before.includes(pattern)) {
      throw new Error(
        `[with-ndk-version] expected "${pattern}" in android/app/build.gradle, ` +
          "but it was not found; the NDK pin was not applied.",
      );
    }
    config.modResults.contents = before.replace(
      pattern,
      `ndkVersion "${NDK_VERSION}"`,
    );
    return config;
  });
};
